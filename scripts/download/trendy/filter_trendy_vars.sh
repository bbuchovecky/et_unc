#!/usr/bin/env bash
# Write a download script for the GCB/TRENDY files of the given variables,
# taken from download_files.sh. SOURCE picks the DGVM outputs (land/output,
# default) or the forcing inputs (land/input). Usage:
#   ./filter_trendy_vars.sh evapotrans tran evspsblsoi evspsblveg lai > et.sh
#   SOURCE=input ./filter_trendy_vars.sh pre tmp spfh dlwrf tswrf > met.sh
#
# Outputs are named <MODEL>_S<n>_<var>[_PFT<nn>].nc[.gz|.tar.gz], and a variable
# matches exactly ("gpp" does not match "gpppft"; CLM's _PFT<nn> files are kept).
# Only the S2 and S3 experiments are kept.
#
# Inputs have no common naming (crujra.v3.5d.<var>.<year>..., <var>_gcb2025_
# <year>..., cldfrac_scaled_<year>...), so a variable matches a word of the
# file name delimited by "." or "_" ("pre" does not match "pres"). Inputs are
# shared by every experiment, so no experiment filter applies.
#
# The generated script downloads into MODEL/EXPT/ (outputs) or DIR/ (inputs,
# e.g. crujra3/, Radiation/) under the current directory, since some models
# reuse file names (e.g. CLASSIC/S2 and CLASSIC/correctedS2). It decompresses
# .nc.gz (SDGVM, VISIT, CRU-JRA, Radiation) and .nc.tar.gz (iMAPLE) files into
# .nc, and skips files whose .nc is already there.

set -euo pipefail

if (( $# == 0 )); then
  echo "usage: [SOURCE=input|output] $(basename "$0") VAR [VAR ...] > out.sh" >&2
  exit 2
fi

infile="$(dirname "$0")/download_files.sh"
vars=$(IFS='|'; echo "$*")
source=${SOURCE:-output}
expts='S[23]'

# Regex of the download lines of the variable(s) $1 ("a|b|...")
pattern() {
  case $source in
    output) echo "/land/output/.*_${expts}_($1)(_PFT[0-9]+)?\.[^/]*\"$" ;;
    input)  echo "/land/input/(.*/)?([^/]*[._])?($1)[._][^/]*\"$" ;;
    *) echo "SOURCE must be input or output, not '$source'" >&2; exit 2 ;;
  esac
}
pattern "$vars" > /dev/null  # check SOURCE before writing anything

cat <<HEADER
#!/bin/bash
# Generated by: SOURCE=$source $(basename "$0") $*

# Download URL \$1 under the current directory and decompress it, unless its .nc exists
get() {
  local f=\${1#*/land/${source}/}
  local nc=\${f%.gz}; nc=\${nc%.tar}
  [[ -e \$nc ]] && return
  wget -x -nH --cut-dirs=3 "\$1" || return
  case \$f in
    *.tar.gz) tar -xzf "\$f" -C "\$(dirname "\$f")" && rm "\$f" ;;
    *.gz)     gunzip "\$f" ;;
  esac
}

HEADER
grep -E "$(pattern "$vars")" "$infile" | sed 's/^wget /get /' || true

# Number of files per variable, on stderr
for v in "$@"; do
  n=$(grep -cE "$(pattern "$v")" "$infile" || true)
  echo "$v: $n files" >&2
done
