#!/usr/bin/env bash
# Write a download script for the GCB/TRENDY DGVM outputs (land/output) of the
# given variables, taken from download_files.sh. Usage:
#   ./filter_trendy_vars.sh evapotrans tran evspsblsoi evspsblveg lai > et.sh
#
# Files are named <MODEL>_S<n>_<var>[_PFT<nn>].nc[.gz|.tar.gz], and a variable
# matches exactly ("gpp" does not match "gpppft"; CLM's _PFT<nn> files are kept).
# Only the S2 and S3 experiments are kept.
#
# The generated script downloads into MODEL/EXPT/ under the current directory,
# since some models reuse file names (e.g. CLASSIC/S2 and CLASSIC/correctedS2).
# It decompresses .nc.gz (SDGVM, VISIT) and .nc.tar.gz (iMAPLE) files into
# .nc, and skips files whose .nc is already there.

set -euo pipefail

if (( $# == 0 )); then
  echo "usage: $(basename "$0") VAR [VAR ...] > out.sh" >&2
  exit 2
fi

infile="$(dirname "$0")/download_files.sh"
vars=$(IFS='|'; echo "$*")
expts='S[23]'

cat <<HEADER
#!/bin/bash
# Generated by: $(basename "$0") $*

# Download URL \$1 into MODEL/EXPT/ and decompress it, unless its .nc exists
get() {
  local f=\${1#*/land/output/}
  local nc=\${f%.gz}; nc=\${nc%.tar}
  [[ -e \$nc ]] && return
  wget -x -nH --cut-dirs=3 "\$1" || return
  case \$f in
    *.tar.gz) tar -xzf "\$f" -C "\$(dirname "\$f")" && rm "\$f" ;;
    *.gz)     gunzip "\$f" ;;
  esac
}

HEADER
grep -E "/land/output/.*_${expts}_(${vars})(_PFT[0-9]+)?\.[^/]*\"$" "$infile" \
  | sed 's/^wget /get /' || true

# Number of files per variable, on stderr
for v in "$@"; do
  n=$(grep -cE "/land/output/.*_${expts}_${v}(_PFT[0-9]+)?\.[^/]*\"$" "$infile" || true)
  echo "$v: $n files" >&2
done
